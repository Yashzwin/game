  x.fillStyle=grd;x.fillRect(0,0,800,400);
  stars.forEach(s=>{s.x-=s.s;if(s.x<0)s.x=800;x.fillStyle='rgba(201,168,76,'+(0.25+s.r/3)+')';
    x.beginPath();x.arc(s.x,s.y,s.r,0,7);x.fill();});
  x.fillStyle='#1c1c28';x.fillRect(0,G-30,800,400-G+30);
  x.strokeStyle='rgba(201,168,76,.5)';x.beginPath();x.moveTo(0,G-30);x.lineTo(800,G-30);x.stroke();
