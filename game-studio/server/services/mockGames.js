  obstacles=obstacles.filter(o=>o.x>-60);
  const px=110,pw=34,ph=34,py=G-30+player.y;
  for(const o of obstacles){
    const ox=o.x,oy=G-30-o.h,ow=26,oh=o.h;
    if(px<ox+ow&&px+pw>ox&&py<oy+oh&&py+ph>oy){dead=true;
      document.getElementById('fs').textContent='Score: '+Math.floor(score);
      document.getElementById('g').style.display='flex';}
  }
  score+=0.1;speed=Math.min(11,speed+0.0015);
